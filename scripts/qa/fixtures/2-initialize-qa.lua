-- Run after native plugin construction, without reading old WeUI settings first.
local root = assert(os.getenv("WEUI_INITIALIZE_QA_ROOT"))
local phase = assert(os.getenv("WEUI_INITIALIZE_QA_PHASE"))
local UIManager = require("ui/uimanager")
G_reader_settings:saveSetting("home_dir", root .. "/library")
G_reader_settings:saveSetting("lastdir", root .. "/library")
local started = false
require("userpatch").registerPatchPluginFunc("weui", function()
    if started then return end
    started = true
    UIManager:scheduleIn(2, function()
        local ok, err = xpcall(function()
            local FM = require("apps/filemanager/filemanager")
            local plugin = assert(FM.instance._weui_plugin, "WeUI instance missing")
            local Store = require("weui_store")
            local Config = require("weui_config")
            local lfs = require("libs/libkoreader-lfs")
            local settings = require("datastorage"):getSettingsDir()
            assert(not lfs.attributes(root .. "/legacy-executed"), "legacy settings were executed")
            assert(not lfs.attributes(root .. "/legacy-plugin-executed"), "duplicate plugin initialized")
            assert(not lfs.attributes(plugin.path .. "/weui-initialize.request"), "request not consumed")
            assert(G_reader_settings:readSetting("start_with") == "filemanager", "home auto-start returned")
            assert(Store:isTrue("weui_weread_lazy_init"))
            assert(plugin._weread_plugin == nil, "WeRead initialized during cold startup")
            assert(not require("weui_paper")._instance, "startup unexpectedly opened Paper")
            assert(G_reader_settings:readSetting("weui_bad_legacy") == nil)
            assert(G_reader_settings:readSetting("simpleui_bad_legacy") == nil)
            assert(lfs.attributes(root .. "/weread/cache/keep.epub", "mode") == "file")
            assert(lfs.attributes(root .. "/library/book.txt", "mode") == "file")
            local native = require("docsettings"):open(root .. "/library/book.txt")
            assert(native:readSetting("percent_finished") == 0.42)
            assert(native:readSetting("annotations")[1].note == "keep note")
            local collections = require("luasettings"):open(settings .. "/collection.lua")
            assert(collections:readSetting("Keep")[1].file == root .. "/library/book.txt")
            assert(Store:get("weui_bar_mode") == (phase == "initialize" and "both" or "labels"))
            local wr = assert(plugin:_initWeReadModule(), "lazy WeRead entry failed")
            local saved = require("luasettings"):open(settings .. "/weread.lua")
            if phase == "initialize" then
                assert(saved:readSetting("api_key", "") == "", "old account restored")
                assert(not next(saved:readSetting("cookies", {})), "old cookie restored")
                assert(Store:get("weui_privacy_password") == nil, "old private settings restored")
            else
                assert(saved:readSetting("api_key") == "new-fixture-key", "new account was reset")
                assert(saved:readSetting("cookies").wr_skey == "new-fixture-cookie", "new login lost")
                assert(Store:get("weui_privacy_password") == "new-fixture-password", "new preferences lost")
            end
            assert(wr and saved:readSetting("download_dir") == root .. "/weread/cache-initialized-1.5.4")
            -- Paint and navigate the actual clean profile at a Kindle resolution.
            local Paper = require("weui_paper")
            for _, id in ipairs(Config.DEFAULT_TABS) do
                local page = assert(Paper.navigate(plugin, id))
                assert(page.screen == id and #page.items > 0)
                UIManager:forceRePaint()
            end
            Store:set("weui_bar_mode", "labels")
            Store:set("weui_privacy_password", "new-fixture-password")
            saved:saveSetting("auth_schema_version", 1)
            saved:saveSetting("api_key", "new-fixture-key")
            saved:saveSetting("cookies", { wr_skey = "new-fixture-cookie" })
            saved:saveSetting("account", { name = "New fixture", user_vid = "new-fixture" })
            saved:flush()
            local pass = assert(io.open(root .. "/artifacts/" .. phase .. ".pass", "w"))
            pass:write("PASS: ", phase, " reset/lazy startup, pages, retained books/native data, persisted new settings\n")
            pass:close()
        end, debug.traceback)
        if not ok then require("logger").err("Initialization QA:", err) end
        UIManager:quit(ok and 0 or 1)
    end)
end)
